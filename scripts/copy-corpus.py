#!/usr/bin/env python3
"""Copy per-language examples/tests into webapp/assets/corpus/.

Driven entirely by webapp/gen/corpus-manifest.json (generated by
racket/metagen.rkt from the repository tree), so the browser
corpus can never drift from the code CI compiles. Invoked by the
Makefile webapp-assets target.
"""
import json
import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main() -> int:
    manifest = json.loads((ROOT / "webapp/gen/corpus-manifest.json").read_text())
    dest_root = ROOT / "webapp/assets/corpus"
    if dest_root.exists():
        shutil.rmtree(dest_root)
    copied = 0
    for lang, entry in sorted(manifest["languages"].items()):
        for group, dir_key in (("examples", "examplesDir"), ("tests", "testsDir")):
            for rel in entry[group]:
                src = ROOT / entry[dir_key] / rel
                dest = dest_root / lang / group / rel
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(src, dest)
                copied += 1
    # Bundled schemas for the Browse schema picker.
    testdata = ROOT / "webapp/assets/testdata"
    if testdata.exists():
        shutil.rmtree(testdata)
    testdata.mkdir(parents=True)
    for schema in manifest["schemas"]:
        if schema["dir"] == "testdata":
            for name in schema["files"]:
                shutil.copyfile(ROOT / "webapp/testdata" / name, testdata / name)
                copied += 1
    print(f"copy-corpus: {copied} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
